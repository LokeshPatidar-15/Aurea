from datetime import datetime, timedelta, timezone
from decimal import Decimal

from sqlalchemy import func, inspect, select
from sqlalchemy.exc import DBAPIError
from sqlalchemy.orm import Session

import models  # noqa: F401  (registers every table on Base.metadata)
from database import Base, engine
from models import PriceHistory, Trade, User
from services.trade_service import calculate_pnl


def section(title: str) -> None:
    print(f"\n=== {title} ===")


def make_trade(symbol, direction, entry, exit_, qty, notes=""):
    entry, exit_, qty = Decimal(entry), Decimal(exit_), Decimal(qty)
    return Trade(
        symbol=symbol,
        direction=direction,
        entry_price=entry,
        exit_price=exit_,
        quantity=qty,
        pnl=calculate_pnl(entry, exit_, qty, direction),
        notes=notes,
    )


def try_insert(label, obj):
    with Session(engine) as session:
        try:
            session.add(obj)
            session.commit()
            print(f"{label}: SAVED (unexpected)")
        except DBAPIError as e:
            session.rollback()
            print(f"{label}: rejected by database ({type(e.orig).__name__})")


def run_demo():
    section("1. Tables created from models")
    ours = sorted(t for t in inspect(engine).get_table_names() if t in Base.metadata.tables)
    print(ours)

    section("2. CREATE: user with 3 trades (pnl computed by the same service as the API)")
    with Session(engine) as session:
        user = User(email="trader@aurea.dev", hashed_password="not-a-real-hash")
        user.trades = [
            make_trade("BTCUSDT", "long", "61200", "63480", "0.05", "liquidity sweep"),
            make_trade("XAUUSD", "long", "1961.2", "1952.4", "2", "against ML signal"),
            make_trade("EURUSD", "short", "1.0950", "1.0900", "2000"),
        ]
        session.add(user)
        session.commit()
        print("user id:", user.id, "| trade ids:", [t.id for t in user.trades])

    section("3. READ (SQL generated by SQLAlchemy is printed below)")
    engine.echo = True
    with Session(engine) as session:
        trades = session.scalars(select(Trade).order_by(Trade.id)).all()
        losing = session.scalars(select(Trade).where(Trade.pnl < 0)).all()
        count, total = session.execute(select(func.count(Trade.id), func.sum(Trade.pnl))).one()
        owner = session.scalars(select(User)).one()
        owned_symbols = [t.symbol for t in owner.trades]
    engine.echo = False
    print("\nall trades:", [(t.id, t.symbol, t.direction, str(t.pnl)) for t in trades])
    print("losing trades:", [t.symbol for t in losing])
    print("count, total pnl:", count, total)
    print("user.trades via relationship:", owned_symbols)

    section("4. UPDATE: change notes on the XAUUSD trade")
    with Session(engine) as session:
        trade = session.scalars(select(Trade).where(Trade.symbol == "XAUUSD")).one()
        trade.notes = "reviewed"
        session.commit()
    with Session(engine) as session:
        print("notes now:", session.scalars(select(Trade.notes).where(Trade.symbol == "XAUUSD")).one())

    section("5. DELETE: remove the EURUSD trade")
    with Session(engine) as session:
        trade = session.scalars(select(Trade).where(Trade.symbol == "EURUSD")).one()
        session.delete(trade)
        session.commit()
        print("trades left:", session.scalar(select(func.count(Trade.id))))

    section("6. CONSTRAINTS: the database rejects bad data")
    try_insert(
        "negative quantity",
        Trade(symbol="BTCUSDT", direction="long", entry_price=Decimal("100"),
              exit_price=Decimal("110"), quantity=Decimal("-1"), pnl=Decimal("0")),
    )
    try_insert(
        "direction 'buy' (fits the column, but CHECK forbids it)",
        Trade(symbol="BTCUSDT", direction="buy", entry_price=Decimal("100"),
              exit_price=Decimal("110"), quantity=Decimal("1"), pnl=Decimal("0")),
    )
    try_insert(
        "direction 'sideways' (longer than VARCHAR(5))",
        Trade(symbol="BTCUSDT", direction="sideways", entry_price=Decimal("100"),
              exit_price=Decimal("110"), quantity=Decimal("1"), pnl=Decimal("0")),
    )
    try_insert("duplicate email", User(email="trader@aurea.dev", hashed_password="x"))

    section("7. CASCADE: deleting a user deletes their trades")
    with Session(engine) as session:
        user = session.scalars(select(User)).one()
        session.delete(user)
        session.commit()
        print("trades remaining:", session.scalar(select(func.count(Trade.id))))

    section("8. PriceHistory: candles with a composite primary key")
    base = datetime(2026, 10, 23, 6, 0, tzinfo=timezone.utc)
    rows = [
        ("63500", "63550", "63480", "63520", "12.5"),
        ("63520", "63580", "63510", "63570", "9.8"),
        ("63570", "63600", "63540", "63550", "7.1"),
    ]
    with Session(engine) as session:
        for i, (o, h, l, c, v) in enumerate(rows):
            session.add(PriceHistory(
                symbol="BTCUSDT", timeframe="1m", open_time=base + timedelta(minutes=i),
                open=Decimal(o), high=Decimal(h), low=Decimal(l), close=Decimal(c), volume=Decimal(v),
            ))
        session.commit()
        print("candles saved:", session.scalar(select(func.count()).select_from(PriceHistory)))
    try_insert(
        "duplicate candle (same symbol, timeframe, open_time)",
        PriceHistory(symbol="BTCUSDT", timeframe="1m", open_time=base, open=Decimal("1"),
                     high=Decimal("2"), low=Decimal("1"), close=Decimal("2"), volume=Decimal("1")),
    )
    try_insert(
        "invalid candle (high below low)",
        PriceHistory(symbol="BTCUSDT", timeframe="1m", open_time=base + timedelta(minutes=10),
                     open=Decimal("5"), high=Decimal("1"), low=Decimal("4"), close=Decimal("3"),
                     volume=Decimal("1")),
    )


def main():
    Base.metadata.drop_all(engine)
    Base.metadata.create_all(engine)
    try:
        run_demo()
    finally:
        Base.metadata.drop_all(engine)
        print("\nCleaned up: demo tables dropped (Alembic creates the real ones on Day 30).")


if __name__ == "__main__":
    main()
